"""Word export of a finished report (python-docx, pure Python).

Input is the Markdown report of the engines plus the structured sources (service/report.py). Output: title, a header
block (question, date, preset, depth), headings, paragraphs, bullet and numbered lists, Markdown tables as real Word tables,
citations `[n]` as links to the source list, the full source list with clickable hyperlinks, Stand and retrieval date,
and a footer with page number and a note that the file was generated by Bebbi Deep Research."""

import io
import re
from datetime import datetime
from zoneinfo import ZoneInfo

from docx import Document
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.opc.constants import RELATIONSHIP_TYPE as RT
from docx.oxml import OxmlElement
from docx.oxml.ns import qn
from docx.shared import Cm, Pt, RGBColor

from .report import source_label, split_report

MIME = "application/vnd.openxmlformats-officedocument.wordprocessingml.document"
BLUE = RGBColor(0x1F, 0x4E, 0x9C)
GREY = RGBColor(0x59, 0x59, 0x59)
PRESET_LABELS = {"rechtsrecherche": "Recht", "grossrat": "Grosser Rat", "statistik": "Statistik",
                 "verwaltung_web": "Verwaltung", "web_survey": "Web"}
LABELS = {
    "de": {"question": "Frage", "date": "Datum", "preset": "Recherchetyp", "depth": "Tiefe", "sources": "Quellen",
           "stand": "Stand", "fetched": "abgerufen am", "no_url": "keine öffentliche URL", "kind": "Art der Quelle",
           "footer": "Erstellt mit Bebbi Deep Research", "page": "Seite", "title": "Recherchebericht"},
    "en": {"question": "Question", "date": "Date", "preset": "Research type", "depth": "Depth", "sources": "Sources",
           "stand": "dated", "fetched": "accessed", "no_url": "no public URL", "kind": "Source type",
           "footer": "Generated by Bebbi Deep Research", "page": "Page", "title": "Research report"},
}
DEPTHS = {"quick": "schnell (quick)", "standard": "Standard", "deep": "gründlich (deep)"}

_INLINE = re.compile(
    r"\*\*(?P<b>.+?)\*\*|(?<![\w*])\*(?P<i>[^*\s][^*]*?)\*(?![\w*])|`(?P<c>[^`]+)`"
    r"|\[(?P<lt>[^\]]+)\]\((?P<lu>https?://[^)\s]+)\)|(?P<url>https?://[^\s)<>\]]+)|\[(?P<n>\d+)\]")
_TABLE_SEP = re.compile(r"^\s*\|?\s*:?-{2,}:?\s*(\|\s*:?-{2,}:?\s*)*\|?\s*$")
_LIST = re.compile(r"^(\s*)([-*+]|\d+[.)])\s+(.*)$")


# ------------------------------------------------------------------ low level helpers
def _style_run(run, bold=False, italic=False, mono=False, color=None, underline=False, size=None, superscript=False):
    run.bold = bold or None
    run.italic = italic or None
    run.underline = underline or None
    if mono:
        run.font.name = "Consolas"
        run._element.rPr.rFonts.set(qn("w:eastAsia"), "Consolas")
    if color is not None:
        run.font.color.rgb = color
    if size:
        run.font.size = Pt(size)
    if superscript:
        run.font.superscript = True


def _hyperlink(paragraph, text: str, url: str | None = None, anchor: str | None = None, **style):
    """External hyperlink (url) or link to a bookmark in the document (anchor)."""
    link = OxmlElement("w:hyperlink")
    if url:
        link.set(qn("r:id"), paragraph.part.relate_to(url, RT.HYPERLINK, is_external=True))
    else:
        link.set(qn("w:anchor"), anchor or "")
    link.set(qn("w:history"), "1")
    run = paragraph.add_run(text)
    _style_run(run, color=BLUE, underline=True, **style)
    paragraph._p.remove(run._r)
    link.append(run._r)
    paragraph._p.append(link)


def _bookmark(paragraph, name: str, ident: int):
    start = OxmlElement("w:bookmarkStart")
    start.set(qn("w:id"), str(ident))
    start.set(qn("w:name"), name)
    end = OxmlElement("w:bookmarkEnd")
    end.set(qn("w:id"), str(ident))
    paragraph._p.insert(0, start)
    paragraph._p.append(end)


def _field(paragraph, instruction: str):
    """A simple field such as PAGE (Word fills the value in when it opens the file); one run per part, all styled."""
    for kind, text in (("begin", None), ("instr", instruction), ("separate", None), ("text", "1"), ("end", None)):
        run = paragraph.add_run()
        if kind == "instr":
            el = OxmlElement("w:instrText")
            el.set(qn("xml:space"), "preserve")
            el.text = f" {text} "
        elif kind == "text":
            el = OxmlElement("w:t")
            el.text = text
        else:
            el = OxmlElement("w:fldChar")
            el.set(qn("w:fldCharType"), kind)
        run._r.append(el)
        _style_run(run, color=GREY, size=9)


def _shade(cell, fill: str):
    tc_pr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement("w:shd")
    shd.set(qn("w:val"), "clear")
    shd.set(qn("w:color"), "auto")
    shd.set(qn("w:fill"), fill)
    tc_pr.append(shd)


def _repeat_header(row):
    pr = row._tr.get_or_add_trPr()
    el = OxmlElement("w:tblHeader")
    el.set(qn("w:val"), "true")
    pr.append(el)


# ------------------------------------------------------------------ inline markdown
def add_inline(paragraph, text: str, cited: set[int] | None = None, **base):
    """Markdown inline elements into runs: **bold**, *italic*, `code`, [text](url), bare URLs, and [n] as links to
    the source list (only for numbers that exist there)."""
    pos = 0
    for m in _INLINE.finditer(text):
        if m.start() > pos:
            _style_run(paragraph.add_run(text[pos:m.start()]), **base)
        pos = m.end()
        if m.group("b") is not None:
            add_inline(paragraph, m.group("b"), cited, **{**base, "bold": True})
        elif m.group("i") is not None:
            add_inline(paragraph, m.group("i"), cited, **{**base, "italic": True})
        elif m.group("c") is not None:
            _style_run(paragraph.add_run(m.group("c")), **{**base, "mono": True})
        elif m.group("lt") is not None:
            _hyperlink(paragraph, m.group("lt"), url=m.group("lu"))
        elif m.group("url") is not None:
            url = m.group("url").rstrip(".,;:")
            _hyperlink(paragraph, url, url=url)
            if len(url) < len(m.group("url")):
                _style_run(paragraph.add_run(m.group("url")[len(url):]), **base)
        else:
            n = int(m.group("n"))
            if cited is not None and n in cited:
                _hyperlink(paragraph, f"[{n}]", anchor=f"quelle_{n}")
            else:
                _style_run(paragraph.add_run(m.group(0)), **base)
    if pos < len(text):
        _style_run(paragraph.add_run(text[pos:]), **base)


# ------------------------------------------------------------------ blocks
def _split_row(line: str) -> list[str]:
    line = line.strip()
    if line.startswith("|"):
        line = line[1:]
    if line.endswith("|"):
        line = line[:-1]
    return [c.strip() for c in re.split(r"(?<!\\)\|", line)]


def add_table(doc, rows: list[list[str]], cited: set[int] | None):
    cols = max(len(r) for r in rows)
    table = doc.add_table(rows=len(rows), cols=cols)
    table.style = "Table Grid"
    for i, row in enumerate(rows):
        for j in range(cols):
            cell = table.cell(i, j)
            p = cell.paragraphs[0]
            p.paragraph_format.space_after = Pt(2)
            add_inline(p, row[j].replace("\\|", "|") if j < len(row) else "", cited, bold=i == 0, size=10)
            if i == 0:
                _shade(cell, "E7ECF4")
    _repeat_header(table.rows[0])
    doc.add_paragraph().paragraph_format.space_after = Pt(2)


def add_markdown(doc, md: str, cited: set[int] | None, skip_title: str | None = None):
    lines = md.splitlines()
    i, para_buf = 0, []
    counters: dict[int, int] = {}

    def flush():
        if para_buf:
            p = doc.add_paragraph()
            p.paragraph_format.space_after = Pt(6)
            add_inline(p, " ".join(s.strip() for s in para_buf), cited)
            para_buf.clear()

    while i < len(lines):
        line = lines[i]
        stripped = line.strip()
        if not stripped:
            flush()
            counters.clear()
            i += 1
        elif stripped.startswith("```"):
            flush()
            i += 1
            code = []
            while i < len(lines) and not lines[i].strip().startswith("```"):
                code.append(lines[i])
                i += 1
            i += 1
            p = doc.add_paragraph()
            _style_run(p.add_run("\n".join(code)), mono=True, size=9)
        elif re.match(r"^#{1,6}\s+", stripped):
            flush()
            hashes, _, text = stripped.partition(" ")
            text = text.strip()
            if len(hashes) == 1 and skip_title is not None and text == skip_title:
                i += 1
                continue
            h = doc.add_heading(level=min(len(hashes), 4))
            add_inline(h, text, cited)
            i += 1
        elif stripped.startswith("|") and i + 1 < len(lines) and _TABLE_SEP.match(lines[i + 1]):
            flush()
            rows = [_split_row(line)]
            i += 2
            while i < len(lines) and lines[i].strip().startswith("|"):
                rows.append(_split_row(lines[i]))
                i += 1
            add_table(doc, rows, cited)
        elif re.match(r"^(-{3,}|\*{3,}|_{3,})$", stripped):
            flush()
            i += 1
        elif stripped.startswith(">"):
            flush()
            p = doc.add_paragraph()
            p.paragraph_format.left_indent = Cm(0.8)
            add_inline(p, stripped.lstrip("> ").strip(), cited, italic=True)
            i += 1
        elif (m := _LIST.match(line)):
            flush()
            depth = min(len(m.group(1).replace("\t", "    ")) // 2, 3)
            ordered = m.group(2)[0].isdigit()
            if ordered:
                counters[depth] = counters.get(depth, 0) + 1
                for d in [d for d in counters if d > depth]:
                    del counters[d]
                p = doc.add_paragraph()
                p.paragraph_format.left_indent = Cm(0.9 + 0.8 * depth)
                p.paragraph_format.first_line_indent = Cm(-0.6)
                p.paragraph_format.space_after = Pt(3)
                p.add_run(f"{counters[depth]}.\t")
                p.paragraph_format.tab_stops.add_tab_stop(Cm(0.9 + 0.8 * depth))
            else:
                p = doc.add_paragraph(style="List Bullet" if depth == 0 else f"List Bullet {min(depth + 1, 3)}")
                p.paragraph_format.space_after = Pt(3)
            add_inline(p, m.group(3), cited)
            i += 1
            # continuation lines (indented, not a new item)
            while i < len(lines) and lines[i].strip() and not _LIST.match(lines[i]) and lines[i].startswith((" ", "\t")):
                add_inline(p, " " + lines[i].strip(), cited)
                i += 1
        else:
            para_buf.append(line)
            i += 1
    flush()


def kind_label(kind: str, de: bool = True) -> str:
    return source_label(kind, de)


def add_sources(doc, sources: list[dict], L: dict):
    doc.add_heading(L["sources"], level=1)
    for s in sources:
        p = doc.add_paragraph()
        p.paragraph_format.left_indent = Cm(1.0)
        p.paragraph_format.first_line_indent = Cm(-1.0)
        p.paragraph_format.space_after = Pt(5)
        p.paragraph_format.keep_together = True
        _style_run(p.add_run(f"[{s['n']}]\t"), bold=True)
        p.paragraph_format.tab_stops.add_tab_stop(Cm(1.0))
        _style_run(p.add_run(s["title"]), bold=True)
        p.add_run().add_break()
        if s["url"]:
            _hyperlink(p, s["url"], url=s["url"], size=10)
        else:
            _style_run(p.add_run(L["no_url"]), italic=True, color=GREY, size=10)
        when = "; ".join(x for x in (f"{L['stand']} {s['stand']}" if s["stand"] else "",
                                      f"{L['fetched']} {s['fetched']}" if s["fetched"] else "",
                                      f"{L['kind']}: {kind_label(s['kind'], L is LABELS['de'])}" if s.get("kind") else "") if x)
        if when:
            p.add_run().add_break()
            _style_run(p.add_run(when), color=GREY, size=9)
        _bookmark(p, f"quelle_{s['n']}", s["n"])


# ------------------------------------------------------------------ document
def _setup(doc, L: dict, title: str):
    sec = doc.sections[0]
    sec.page_width, sec.page_height = Cm(21.0), Cm(29.7)
    sec.left_margin = sec.right_margin = Cm(2.3)
    sec.top_margin, sec.bottom_margin = Cm(2.2), Cm(2.2)
    normal = doc.styles["Normal"]
    normal.font.name = "Calibri"
    normal.font.size = Pt(11)
    normal.element.rPr.rFonts.set(qn("w:eastAsia"), "Calibri")
    normal.paragraph_format.line_spacing = 1.15
    for name, size in (("Title", 22), ("Heading 1", 16), ("Heading 2", 13), ("Heading 3", 12), ("Heading 4", 11)):
        st = doc.styles[name]
        st.font.name = "Calibri"
        st.font.size = Pt(size)
        st.font.color.rgb = RGBColor(0x1F, 0x2F, 0x4F)
        st.element.rPr.rFonts.set(qn("w:eastAsia"), "Calibri")
        st.element.rPr.rFonts.set(qn("w:ascii"), "Calibri")
        st.element.rPr.rFonts.set(qn("w:hAnsi"), "Calibri")
    lang = OxmlElement("w:lang")
    lang.set(qn("w:val"), "de-CH" if L is LABELS["de"] else "en-GB")
    normal.element.rPr.append(lang)
    footer = sec.footer.paragraphs[0]
    footer.alignment = WD_ALIGN_PARAGRAPH.CENTER
    _style_run(footer.add_run(f"{L['footer']} · {L['page']} "), color=GREY, size=9)
    _field(footer, "PAGE")
    props = doc.core_properties
    props.title, props.author, props.last_modified_by = title, "Bebbi Deep Research", "Bebbi Deep Research"
    props.language = "de-CH" if L is LABELS["de"] else "en-GB"


def render_docx(report: str, sources: list[dict], *, task: str = "", preset: str = "", depth: str = "",
                finished: float | None = None, tz: str = "Europe/Zurich") -> bytes:
    """The Word file for one report. `sources` from service.report.build_sources; if empty, the report is rendered as is."""
    body, heading, _ = split_report(report)
    L = LABELS["en" if heading == "Sources" else "de"]
    if not sources:
        body = report
    title_match = re.match(r"\s*#\s+(.+?)\s*\n", body)
    title = title_match.group(1).strip() if title_match else L["title"]
    doc = Document()
    _setup(doc, L, title)
    doc.add_paragraph(title, style="Title")

    when = datetime.fromtimestamp(finished, ZoneInfo(tz)) if finished else datetime.now(ZoneInfo(tz))
    info = [(L["question"], " ".join(task.split())), (L["date"], when.strftime("%d.%m.%Y, %H:%M")),
            (L["preset"], PRESET_LABELS.get(preset, preset) + (f" ({preset})" if preset in PRESET_LABELS else "")),
            (L["depth"], DEPTHS.get(depth, depth))]
    table = doc.add_table(rows=0, cols=2)
    table.style = "Table Grid"
    table.autofit = False
    table.columns[0].width, table.columns[1].width = Cm(3.6), Cm(12.8)
    for k, v in info:
        if not v.strip():
            continue
        cells = table.add_row().cells
        cells[0].width, cells[1].width = Cm(3.6), Cm(12.8)
        _shade(cells[0], "E7ECF4")
        _style_run(cells[0].paragraphs[0].add_run(k), bold=True, size=10)
        _style_run(cells[1].paragraphs[0].add_run(v), size=10)
    doc.add_paragraph()

    cited = {s["n"] for s in sources}
    add_markdown(doc, body, cited if sources else None, skip_title=title if title_match else None)
    if sources:
        add_sources(doc, sources, L)
    out = io.BytesIO()
    doc.save(out)
    return out.getvalue()


def docx_filename(title: str, finished: float | None = None, tz: str = "Europe/Zurich") -> str:
    """ASCII file name such as `Bebbi-Deep-Research_Fasnacht-im-Grossen-Rat_2026-10-09.docx`."""
    ascii_title = title.translate(str.maketrans({"ä": "ae", "ö": "oe", "ü": "ue", "Ä": "Ae", "Ö": "Oe", "Ü": "Ue", "é": "e", "è": "e", "à": "a"}))
    slug = re.sub(r"[^A-Za-z0-9]+", "-", ascii_title).strip("-")[:60].strip("-") or "Bericht"
    day = (datetime.fromtimestamp(finished, ZoneInfo(tz)) if finished else datetime.now(ZoneInfo(tz))).strftime("%Y-%m-%d")
    return f"Bebbi-Deep-Research_{slug}_{day}.docx"
