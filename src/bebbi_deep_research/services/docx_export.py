_INLINE = re.compile(
    r"\*\*(?P<b>.+?)\*\*|(?<![\w*])\*(?P<i>[^*\s][^*]*?)\*(?![\w*])|`(?P<c>[^`]+)`"
    r"|\[(?P<lt>[^\]]+)\]\((?P<lu>https?://[^)\s]+)\)|(?P<url>https?://[^\s)<>\]]+)|\[(?P<n>\d+)\]"
)
_TABLE_SEP = re.compile(r"^\s*\|?\s*:?-{2,}:?\s*(\|\s*:?-{2,}:?\s*)*\|?\s*$")
_LIST = re.compile(r"^(\s*)([-*+]|\d+[.)])\s+(.*)$")
_HEADING = re.compile(r"^(#{1,6})\s+(.*)$")


@functools.cache
def _template() -> bytes:
    return TEMPLATE.read_bytes()


# ------------------------------------------------------------------ low level helpers
def _style_run(run, bold=False, italic=False, mono=False, size=None):
    run.bold = bold or None
    run.italic = italic or None
    if mono:
        run.font.name = MONO
    if size:
        run.font.size = Pt(size)


def _hyperlink(paragraph, text: str, url: str | None = None, anchor: str | None = None, **style):
    """External hyperlink (url) or link to a bookmark in the document (anchor), in the template's Hyperlink style."""
    link = OxmlElement("w:hyperlink")
    if url:
        link.set(qn("r:id"), paragraph.part.relate_to(url, RT.HYPERLINK, is_external=True))
    else:
        link.set(qn("w:anchor"), anchor or "")
    link.set(qn("w:history"), "1")
    run = paragraph.add_run(text, style=LINK)
    _style_run(run, **style)
    paragraph._p.remove(run._r)
    link.append(run._r)
    paragraph._p.append(link)


def _bookmark(paragraph, name: str, ident: int):
    start = OxmlElement("w:bookmarkStart")
    start.set(qn("w:id"), str(ident))
    start.set(qn("w:name"), name)
    end = OxmlElement("w:bookmarkEnd")
    end.set(qn("w:id"), str(ident))
    paragraph._p.insert(0, start)
    paragraph._p.append(end)


def _shade(cell, fill: str):
    tc_pr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement("w:shd")
    shd.set(qn("w:val"), "clear")
    shd.set(qn("w:color"), "auto")
    shd.set(qn("w:fill"), fill)
    tc_pr.append(shd)


def _repeat_header(row):
    pr = row._tr.get_or_add_trPr()
    el = OxmlElement("w:tblHeader")
    el.set(qn("w:val"), "true")
    pr.append(el)


# List numbering as in kdkp_office.word: each numbered list gets its own w:num on the numbering of the
# ListWithNumbers style, so it counts from its first number; nesting is the list level (w:ilvl).
def _abstract_num_id(doc, style_name: str) -> str | None:
    """The abstract numbering behind a list style, to start new lists from it."""
    try:
        style = doc.styles[style_name]
    except KeyError:
        return None
    num = style.element.find(f"{qn('w:pPr')}/{qn('w:numPr')}/{qn('w:numId')}")
    if num is None:
        return None
    for n in doc.part.numbering_part.element.findall(qn("w:num")):
        if n.get(qn("w:numId")) == num.get(qn("w:val")):
            return n.find(qn("w:abstractNumId")).get(qn("w:val"))
    return None


def _new_numbering(doc, abstract_id: str, level: int, start: int) -> str:
    """A new w:num on the list style's numbering that counts from `start` at `level`; returns its id."""
    numbering = doc.part.numbering_part.element
    num_id = str(max(int(n.get(qn("w:numId"))) for n in numbering.findall(qn("w:num"))) + 1)
    num = OxmlElement("w:num")
    num.set(qn("w:numId"), num_id)
    abstract = OxmlElement("w:abstractNumId")
    abstract.set(qn("w:val"), abstract_id)
    num.append(abstract)
    override = OxmlElement("w:lvlOverride")
    override.set(qn("w:ilvl"), str(level))
    start_el = OxmlElement("w:startOverride")
    start_el.set(qn("w:val"), str(start))
    override.append(start_el)
    num.append(override)
    numbering.append(num)
    return num_id


def _number(p, num_id: str | None, level: int):
    """Set the paragraph's list level and numbering (`num_id` None: the numbering of its style)."""
    if num_id is None and level == 0:
        return
    if num_id is None:
        num = p.style.element.find(f"{qn('w:pPr')}/{qn('w:numPr')}/{qn('w:numId')}")
        num_id = None if num is None else num.get(qn("w:val"))
    numpr = OxmlElement("w:numPr")
    ilvl = OxmlElement("w:ilvl")
    ilvl.set(qn("w:val"), str(level))
    numpr.append(ilvl)
    if num_id is not None:
        nid = OxmlElement("w:numId")
        nid.set(qn("w:val"), num_id)
        numpr.append(nid)
    p._p.get_or_add_pPr().append(numpr)


# ------------------------------------------------------------------ inline markdown
def add_inline(
    paragraph, text: str, cited: set[int] | None = None, *, links: frozenset[str] | set[str] = frozenset(), **base
):
    """Add Markdown inline elements to a paragraph as runs.

    Handles **bold**, *italic*, `code`, [text](url), bare URLs, and [n] as links to the source list (only for numbers
    that exist there). Report text is untrusted (services/report.py `sanitize_markdown`): only URLs in `links`, the
    registered source URLs, become hyperlinks; any other link keeps its text (or the bare URL) as plain text.
    """
    pos = 0
    for m in _INLINE.finditer(text):
        if m.start() > pos:
            _style_run(paragraph.add_run(text[pos : m.start()]), **base)
        pos = m.end()
        if m.group("b") is not None:
            add_inline(paragraph, m.group("b"), cited, links=links, **{**base, "bold": True})
        elif m.group("i") is not None:
            add_inline(paragraph, m.group("i"), cited, links=links, **{**base, "italic": True})
        elif m.group("c") is not None:
            _style_run(paragraph.add_run(m.group("c")), **{**base, "mono": True})
        elif m.group("lt") is not None:
            if m.group("lu") in links:
                _hyperlink(paragraph, m.group("lt"), url=m.group("lu"))
            else:
                add_inline(paragraph, m.group("lt"), cited, links=links, **base)
        elif m.group("url") is not None:
            url = m.group("url").rstrip(".,;:")
            if url in links:
                _hyperlink(paragraph, url, url=url)
            else:
                _style_run(paragraph.add_run(url), **base)
            if len(url) < len(m.group("url")):
                _style_run(paragraph.add_run(m.group("url")[len(url) :]), **base)
        else:
            n = int(m.group("n"))
            if cited is not None and n in cited:
                _hyperlink(paragraph, f"[{n}]", anchor=f"quelle_{n}")
            else:
                _style_run(paragraph.add_run(m.group(0)), **base)
    if pos < len(text):
        _style_run(paragraph.add_run(text[pos:]), **base)


# ------------------------------------------------------------------ blocks
def _split_row(line: str) -> list[str]:
    line = line.strip()
    if line.startswith("|"):
        line = line[1:]
    if line.endswith("|"):
        line = line[:-1]
    return [c.strip() for c in re.split(r"(?<!\\)\|", line)]


def _align(separator: str) -> list:
    """Column alignments of a Markdown table separator row (`:--`, `:-:`, `--:`); None: the default."""
    out = []
    for cell in _split_row(separator):
        left, right = cell.startswith(":"), cell.endswith(":")
        out.append(WD_ALIGN_PARAGRAPH.CENTER if left and right else WD_ALIGN_PARAGRAPH.RIGHT if right else None)
    return out


def add_table(
    doc,
    rows: list[list[str]],
    cited: set[int] | None,
    links: frozenset[str] | set[str] = frozenset(),
    align: list | None = None,
):
    """Add a Markdown table as a Word table (first row as shaded, repeating header; `align` per column)."""
    cols = max(len(r) for r in rows)
    table = doc.add_table(rows=len(rows), cols=cols)
    table.style = TABLE
    table.alignment = WD_TABLE_ALIGNMENT.LEFT
    for i, row in enumerate(rows):
        for j in range(cols):
            cell = table.cell(i, j)
            if align and j < len(align) and align[j] is not None:
                cell.paragraphs[0].alignment = align[j]
            add_inline(
                cell.paragraphs[0], row[j].replace("\\|", "|") if j < len(row) else "", cited, links=links, bold=i == 0
            )
            if i == 0:
                _shade(cell, HEADER_FILL)
    _repeat_header(table.rows[0])
    # Keeps the next paragraph or table from sticking to this one.
    doc.add_paragraph()


def _heading_shift(lines: list[str], skip_title: str | None) -> int:
    """How many levels the headings move up, so the highest level used becomes Heading 1 (as in kdkp_office)."""
    levels, fenced = [], False
    for line in lines:
        stripped = line.strip()
        if stripped.startswith("```"):
            fenced = not fenced
        elif not fenced and (m := _HEADING.match(stripped)):
            if not (len(m.group(1)) == 1 and skip_title is not None and m.group(2).strip() == skip_title):
                levels.append(len(m.group(1)))
    return min(levels, default=1) - 1


def add_markdown(
    doc, md: str, cited: set[int] | None, skip_title: str | None = None, links: frozenset[str] | set[str] = frozenset()
):
    """Add a Markdown report: headings, paragraphs, lists and tables (`skip_title` is not repeated).

    Only URLs in `links` become hyperlinks (see `add_inline`).
    """
    lines = md.splitlines()
    shift = _heading_shift(lines, skip_title)
    numbers = _abstract_num_id(doc, NUMBERS)
    i, para_buf = 0, []
    lists: dict[int, str | None] = {}  # open list per depth: its numbering (None: bullets)
    last_item = None

    def end_list():
        nonlocal last_item
        if last_item is not None:
            last_item.paragraph_format.space_after = BLOCK_GAP
            last_item = None

    def flush():
        if para_buf:
            p = doc.add_paragraph()
            p.paragraph_format.space_after = BLOCK_GAP
            add_inline(p, " ".join(s.strip() for s in para_buf), cited, links=links)
            para_buf.clear()

    while i < len(lines):
        line = lines[i]
        stripped = line.strip()
        if not stripped:
            flush()
            end_list()
            lists.clear()
            i += 1
            continue
        if not _LIST.match(line):
            end_list()
            lists.clear()
        if stripped.startswith("```"):
            flush()
            i += 1
            code = []
            while i < len(lines) and not lines[i].strip().startswith("```"):
                code.append(lines[i])
                i += 1
            i += 1
            code_lines = [doc.add_paragraph(style=CODE) for _ in code or [""]]
            for p, text in zip(code_lines, code or [""], strict=True):
                _style_run(p.add_run(text), mono=True, size=9)
            code_lines[-1].paragraph_format.space_after = BLOCK_GAP
        elif m := _HEADING.match(stripped):
            flush()
            text = m.group(2).strip()
            if len(m.group(1)) == 1 and skip_title is not None and text == skip_title:
                i += 1
                continue
            h = doc.add_heading(level=min(max(len(m.group(1)) - shift, 1), 4))
            add_inline(h, text, cited, links=links)
            i += 1
        elif stripped.startswith("|") and i + 1 < len(lines) and _TABLE_SEP.match(lines[i + 1]):
            flush()
            rows, align = [_split_row(line)], _align(lines[i + 1])
            i += 2
            while i < len(lines) and lines[i].strip().startswith("|"):
                rows.append(_split_row(lines[i]))
                i += 1
            add_table(doc, rows, cited, links, align)
        elif re.match(r"^(-{3,}|\*{3,}|_{3,})$", stripped):
            flush()
            i += 1
        elif stripped.startswith(">"):
            flush()
            p = doc.add_paragraph(style=QUOTE)
            p.paragraph_format.left_indent = Cm(0.75)
            p.paragraph_format.space_after = BLOCK_GAP
            add_inline(p, stripped.lstrip("> ").strip(), cited, links=links)
            i += 1
        elif m := _LIST.match(line):
            flush()
            depth = min(len(m.group(1).replace("\t", "    ")) // 2, MAX_LIST_LEVEL)
            ordered = m.group(2)[0].isdigit()
            for d in [d for d in lists if d > depth]:
                del lists[d]
            if depth == 0 and depth in lists and (lists[depth] is None) == ordered:
                end_list()  # a bullet list right after a numbered one (or the reverse) is a list of its own
            if ordered and (depth not in lists or lists[depth] is None) and numbers is not None:
                lists[depth] = _new_numbering(doc, numbers, depth, int(m.group(2)[:-1]))
            elif not ordered:
                lists[depth] = None
            p = doc.add_paragraph(style=NUMBERS if ordered else BULLETS)
            _number(p, lists.get(depth), depth)
            add_inline(p, m.group(3), cited, links=links)
            last_item = p
            i += 1
            # continuation lines (indented, not a new item)
            while (
                i < len(lines) and lines[i].strip() and not _LIST.match(lines[i]) and lines[i].startswith((" ", "\t"))
            ):
                add_inline(p, " " + lines[i].strip(), cited, links=links)
                i += 1
        else:
            para_buf.append(line)
            i += 1
    flush()
    end_list()


def kind_label(kind: str, de: bool = True) -> str:
    """Return the display label of a source kind."""
    return source_label(kind, de)


def add_sources(doc, sources: list[dict], L: dict):
    """Add the numbered source list with hyperlinks, Stand and retrieval date."""
    doc.add_heading(L["sources"], level=1)
    for s in sources:
        p = doc.add_paragraph()
        p.paragraph_format.left_indent = Cm(1.0)
        p.paragraph_format.first_line_indent = Cm(-1.0)
        p.paragraph_format.space_after = Pt(5)
        p.paragraph_format.keep_together = True
        _style_run(p.add_run(f"[{s['n']}]\t"), bold=True)
        p.paragraph_format.tab_stops.add_tab_stop(Cm(1.0))
        _style_run(p.add_run(s["title"]), bold=True)
        p.add_run().add_break()
        if s["url"]:
            _hyperlink(p, s["url"], url=s["url"], size=10)
        else:
            _style_run(p.add_run(L["no_url"]), italic=True, size=10)
        when = "; ".join(
            x
            for x in (
                f"{L['stand']} {s['stand']}" if s["stand"] else "",
                f"{L['fetched']} {s['fetched']}" if s["fetched"] else "",
                f"{L['kind']}: {kind_label(s['kind'], L is LABELS['de'])}" if s.get("kind") else "",
            )
            if x
        )
        if when:
            p.add_run().add_break()
            _style_run(p.add_run(when), size=9)
        _bookmark(p, f"quelle_{s['n']}", s["n"])


# ------------------------------------------------------------------ document
def _footers(doc, L: dict):
    """Put the Bebbi note in front of the template's "Seite n/m" footers (and "Page" for an English report)."""
    for sec in doc.sections:
        for footer in (sec.footer, sec.even_page_footer, sec.first_page_footer):
            if footer.is_linked_to_previous:
                continue
            for p in footer.paragraphs:
                if "PAGE" not in p._p.xml:
                    continue
                for t in p._p.iter(qn("w:t")):
                    if t.text == "Seite ":
                        t.text = f"{L['page']} "
                first = p._p.find(qn("w:r"))
                note = p.add_run(f"{L['footer']} · ")._r
                if first is not None:
                    first.addprevious(note)


def _setup(doc, L: dict, title: str, when: datetime):
    if L is not LABELS["de"]:
        rpr = doc.styles["Normal"].element.get_or_add_rPr()
        for old in rpr.findall(qn("w:lang")):
            rpr.remove(old)
        lang = OxmlElement("w:lang")
        lang.set(qn("w:val"), "en-GB")
        rpr.append(lang)
    _footers(doc, L)
    props = doc.core_properties
    props.title, props.author, props.last_modified_by = title, "Bebbi Deep Research", "Bebbi Deep Research"
    props.created = props.modified = when.astimezone(UTC).replace(tzinfo=None)  # python-docx writes it as UTC
    props.revision = 1
    props.language = "de-CH" if L is LABELS["de"] else "en-GB"


def render_docx(
    report: str,
    sources: list[dict],
    *,
    task: str = "",
    preset: str = "",
    depth: str = "",
    finished: float | None = None,
    tz: str = "Europe/Zurich",
) -> bytes:
    """Render one report as Word file and return its bytes.

    `sources` comes from `services.report.build_sources`; if it is empty, the report is rendered as it is. Links in
    the report become hyperlinks only when they point to a URL of `sources` (as in the chat); without sources, none.
    """
    report, task, preset, depth = clean_text(report), clean_text(task), clean_text(preset), clean_text(depth)
    sources = [
        {k: clean_text(v) if isinstance(v, str) else v for k, v in s.items()} for s in sources
    ]  # XML rejects control characters
    body, heading, _ = split_report(report)
    L = LABELS["en" if heading == "Sources" else "de"]
    if not sources:
        body = report
    title_match = re.match(r"\s*#\s+(.+?)\s*\n", body)
    title = title_match.group(1).strip() if title_match else L["title"]
    when = datetime.fromtimestamp(finished, ZoneInfo(tz)) if finished else datetime.now(ZoneInfo(tz))
    doc = Document(io.BytesIO(_template()))
    _setup(doc, L, title, when)
    doc.add_paragraph(title, style="Title").paragraph_format.space_after = BLOCK_GAP

    info = [
        (L["question"], " ".join(task.split())),
        (L["date"], when.strftime("%d.%m.%Y, %H:%M")),
        (L["preset"], PRESET_LABELS.get(preset, preset) + (f" ({preset})" if preset in PRESET_LABELS else "")),
        (L["depth"], DEPTHS.get(depth, depth)),
    ]
    table = doc.add_table(rows=0, cols=2)
    table.style = TABLE
    table.alignment = WD_TABLE_ALIGNMENT.LEFT
    table.autofit = False
    table.columns[0].width, table.columns[1].width = Cm(3.6), Cm(13.2)
    for k, v in info:
        if not v.strip():
            continue
        cells = table.add_row().cells
        cells[0].width, cells[1].width = Cm(3.6), Cm(13.2)
        _shade(cells[0], HEADER_FILL)
        _style_run(cells[0].paragraphs[0].add_run(k), bold=True)
        cells[1].paragraphs[0].add_run(v)
    doc.add_paragraph()

    cited = {s["n"] for s in sources}
    links = frozenset(s["url"] for s in sources if s["url"])  # the registered source URLs, as in the chat
    add_markdown(doc, body, cited if sources else None, skip_title=title if title_match else None, links=links)
    if sources:
        add_sources(doc, sources, L)
    out = io.BytesIO()
    doc.save(out)
    return out.getvalue()


def docx_filename(title: str, finished: float | None = None, tz: str = "Europe/Zurich") -> str:
    """ASCII file name such as `Bebbi-Deep-Research_Fasnacht-im-Grossen-Rat_2026-10-09.docx`."""
    ascii_title = title.translate(
        str.maketrans({"ä": "ae", "ö": "oe", "ü": "ue", "Ä": "Ae", "Ö": "Oe", "Ü": "Ue", "é": "e", "è": "e", "à": "a"})
    )
    slug = re.sub(r"[^A-Za-z0-9]+", "-", ascii_title).strip("-")[:60].strip("-") or "Bericht"
    day = (datetime.fromtimestamp(finished, ZoneInfo(tz)) if finished else datetime.now(ZoneInfo(tz))).strftime(
        "%Y-%m-%d"
    )
    return f"Bebbi-Deep-Research_{slug}_{day}.docx"
