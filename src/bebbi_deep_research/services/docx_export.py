"""Word export of a finished report (python-docx, pure Python) in the Kanton Basel-Stadt layout.

Input is the Markdown report of the engines plus the structured sources (services/report.py). Output: title, a header
block (question, date, preset, depth), headings, paragraphs, bullet and numbered lists, Markdown tables as real Word
tables, citations `[n]` as links to the source list, the full source list with clickable hyperlinks, Stand and
retrieval date, and a footer with page number and a note that the file was generated by Bebbi Deep Research. Links in
the report text become hyperlinks only when they point to a registered source URL.

Page, fonts, sizes, colours, logo and the "Seite n/m" footer come from `assets/word/template.docx`, the template of the
Word files Bebbi Bot's document tools write (`kdkp_office.word` in FD-ITBS/kdkp-open-web-ui, see assets/README.md).
Each element uses the same style as there: `Title`, the numbered `Heading 1` to `Heading 4`, `ListWithBullets`,
`ListWithNumbers`, `Table Grid` with a shaded, repeating header row, `Block Text`, `Plain Text` and `Hyperlink`.

Only the template and the style names are shared, not the renderer. kdkp_office lives in the Open WebUI image, not in
a package this service could depend on; copying its `word.py` and `md.py` (about 770 lines) would bring markdown-it-py,
mdit-py-plugins, latex2mathml and mathml2omml, and still lack what this report needs (header block, `[n]` links to
bookmarked sources, links only to source URLs). The list numbering helpers below are taken from kdkp_office.word.
"""

